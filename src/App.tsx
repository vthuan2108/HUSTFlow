    let streak = 0;
    let curr = new Date(startDate);

    while (true) {
      const dateStr = getLocalDateString(curr);
      if (history[dateStr]) {
        streak++;
        curr.setDate(curr.getDate() - 1);
      } else {
        break;
      }
    }

    return streak;
