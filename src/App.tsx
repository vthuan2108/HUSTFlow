function getLocalDateString(d: Date = new Date()): string {
  const year = d.getFullYear();
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

function sanitizeLegacyBuggyLogs(logs: DailyLog[]): DailyLog[] {
  if (!logs || logs.length === 0) return [];
  const todayStr = getLocalDateString();
  const yesterday = new Date();
  yesterday.setDate(yesterday.getDate() - 1);
  const yesterdayStr = getLocalDateString(yesterday);

  return logs
    .filter(l => {
      // Artificial 1-minute logs with 0 Exp and 0 tasks generated by legacy dao_tam_phu bug
      const isLegacyBug = l.meditationMinutes === 1 && l.tuViGained === 0 && l.tasksCompleted === 0;
      if (!isLegacyBug) return true;
      // Only preserve if it was legitimately healed for yesterday or today
      return l.date === yesterdayStr || l.date === todayStr;
    })
    .map(l => {
      // If it was a healed log, strip the fake 1 minute so it doesn't inflate meditationMinutes
      if (l.meditationMinutes === 1 && l.tuViGained === 0 && l.tasksCompleted === 0) {
        return {
          ...l,
          meditationMinutes: 0,
          isStreakProtected: true
        };
      }
      return l;
    });
}

